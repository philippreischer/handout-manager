CREATE TABLE resource (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by      BIGINT NOT NULL,
    project_id      BIGINT NOT NULL,
    name            VARCHAR(255) NOT NULL,
    resource_type   VARCHAR(30) NOT NULL,
    content         TEXT,
    file_path       VARCHAR(255),
    created_at      TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP WITH TIME ZONE  NOT NULL,

    CONSTRAINT fk_resource_created_by
        FOREIGN KEY (created_by) REFERENCES user_account (id),

    CONSTRAINT fk_resource_project_id
        FOREIGN KEY (project_id) REFERENCES project (id)
);

CREATE INDEX idx_resource_created_by ON resource (created_by);
CREATE INDEX idx_resource_project_id ON resource (project_id);