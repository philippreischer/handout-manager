CREATE TABLE membership (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    project_id      BIGINT NOT NULL,
    nick_name       VARCHAR(255),
    membership_role VARCHAR(30) NOT NULL,

    CONSTRAINT fk_membership_user_id
        FOREIGN KEY (user_id) REFERENCES user_account (id),

    CONSTRAINT fk_membership_project_id
        FOREIGN KEY (project_id) REFERENCES project (id),

    CONSTRAINT uq_membership_user_id_project_id
        UNIQUE (user_id, project_id)
);

CREATE INDEX idx_membership_user_id ON membership (user_id);
CREATE INDEX idx_membership_project_id ON membership (project_id);