CREATE TABLE permission (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    resource_id     BIGINT NOT NULL,

    CONSTRAINT fk_permission_user_id
        FOREIGN KEY (user_id) REFERENCES user_account (id),

    CONSTRAINT fk_permission_resource_id
        FOREIGN KEY (resource_id) REFERENCES resource (id),

    CONSTRAINT uq_permission_user_id_resource_id
        UNIQUE (user_id, resource_id)
);

CREATE INDEX idx_permission_user_id ON permission (user_id);
CREATE INDEX idx_permission_resource_id ON permission (resource_id);